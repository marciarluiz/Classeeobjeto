public class Pessoa {
    private String nome;
    private int idade;

    // Setter - altera o nome
    public void setNome(String nome) {
        this.nome = nome;
    }
    //Getter - retorna o nome
    public String getNome() {
        return nome;
    }
    public void setIdade(int idade) {
        this.idade = idade;
    }
    public int getIdade() {
        return idade;
    }
}